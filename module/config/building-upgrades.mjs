/** Цена строкой «Древесина 5, Камень 2» → [{resource, qty}]. */
const cost = text => (text ? text.split(",").map(s => s.trim()).filter(Boolean).map(s => {
  const m = s.match(/^(.+?)\s+([\d.]+)$/);
  return { resource: m[1], qty: Number(m[2]) };
}) : []);

