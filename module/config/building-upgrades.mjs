/**
 * Дерево встроенной постройки с постоянными id ступеней («b1n2» — 1-я ветка, 2-я ступень; каждая требует предыдущую).
 * @param {string} key
 * @param {number} [maxLevel] — уровней у постройки: ступень не требует уровня выше (у торгового поста один уровень)
 */
export function buildingTree(key, maxLevel = Infinity) {
  const tree = BUILDING_TREES[key];
  if (!tree) return [];
  return tree.map((br, i) => ({
    id: `b${i + 1}`, name: br.name, icon: br.icon,
    nodes: br.nodes.map((nd, j) => ({
      id: `b${i + 1}n${j + 1}`, name: nd.name, description: nd.description, level: Math.min(nd.level, maxLevel), weeks: nd.weeks,
      requires: j ? `b${i + 1}n${j}` : "", cost: nd.cost.map(c => ({ ...c })),
      effects: nd.effects.filter(e => e.formula || e.type === "trade" || e.value).map(e => ({ resource: "", value: 0, formula: "", per: "building", period: "week", ...e }))
    }))
  }));
}

/** Эффект-бросок (kind «dice»): его бросок. Старые данные хранили проценты в value — переводятся как в справочнике. */
export function effectDice(e) {
  const f = String(e?.formula ?? "").trim();
  const v = Number(e?.value) || 0;
  if (v > 0 && (!f || f === "1")) return pctToDice(v, e.type === "revolt" || e.type === "arrival");
  return f;
}

/** Проценты → бросок (перевод PLAN 4.200): выработка и сырьё 10 % — 1d2 … 30 % — 1d8; шансы 5 — 1d6, 10 — 2d6. */
export function pctToDice(v, chance = false) {
  if (chance) return `${Math.max(1, Math.round(v / 5))}d6`;
  if (v <= 5) return "1";
  if (v <= 10) return "1d2";
  if (v <= 15) return "1d3";
  if (v <= 20) return "1d4";
  if (v <= 25) return "1d6";
  if (v <= 30) return "1d8";
  return `${Math.ceil(v / 30)}d8`;
}
