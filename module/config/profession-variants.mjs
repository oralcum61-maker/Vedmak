/** Выбор профессии, если книга его даёт: { label, prompt, hint, options } или null. */
export const variantsOf = prof => PROFESSION_VARIANTS[prof?.system?.key] ?? null;

/** Определяющий навык с выбором: ведьма — навык традиции с её параметром, учёный — навык с предметом. */
export function variantDefining(prof, key) {
  const v = variantsOf(prof);
  const o = v?.options.find(x => x.key === key);
  if (!o) return null;
  const ds = prof.system.definingSkill;
  if (v.mode === "named") return { ...ds, name: o.label, stat: o.stat ?? ds.stat, effect: `${v.label} «${o.label}»: ${o.about}. ${ds.effect ?? ""}`.trim() };
  return { ...ds, name: `${ds.name} (${o.label})`, effect: `Предмет — ${o.label} (${o.about}): +3 к проверкам по нему. ${ds.effect ?? ""}`.trim() };
}

