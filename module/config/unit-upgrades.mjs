/** Ветка с постоянными id ступеней («discipline-2»; каждая требует предыдущую). */
function branchData(br) {
  return { id: br.id, name: br.name, icon: br.icon, nodes: br.nodes.map((nd, j) => ({
    id: `${br.id}-${j + 1}`, name: nd.name, description: nd.description, rank: nd.rank, weapons: nd.weapons, armor: nd.armor,
    weeks: nd.weeks, requires: j ? `${br.id}-${j}` : "", cost: nd.cost.map(c => ({ ...c })),
    effects: nd.effects.map(e => ({ kind: "", terrain: "", formula: "", ...e }))
  })) };
}

/** Дерево отряда рода kind: три общие ветки и ветка рода. */
export function unitTree(kind) {
  return [...COMMON_BRANCHES, KIND_BRANCHES[kind] ?? KIND_BRANCHES.infantry].map(branchData);
}

/** Ветка рода войск для смены рода. */
export const kindBranch = kind => branchData(KIND_BRANCHES[kind] ?? KIND_BRANCHES.infantry);
