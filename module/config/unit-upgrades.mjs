/** Сколько раз бросается эффект-бросок: Новобранцы и Обстрелянные — 1, Ветераны и Закалённые — 2, Элита — 3. */
export const diceTimes = rank => 1 + Math.floor((rank ?? 0) / 2);

/** Эффект-бросок отряда: его бросок; старые данные хранили проценты в value — 10 % → 1d2, 15 % → 1d3, 20 % → 1d4. */
export function unitEffectDice(e) {
  const f = String(e?.formula ?? "").trim();
  const v = Number(e?.value) || 0;
  if (f) return f;
  if (v <= 0) return "";
  return v <= 10 ? "1d2" : v <= 15 ? "1d3" : v <= 20 ? "1d4" : v <= 25 ? "1d6" : "1d8";
}
